function parseUserSettings(userPrompt: string): CarouselUserSettings {
  const settings: CarouselUserSettings = {};
  const templateMatch = userPrompt.match(/Template:\s*([^\n]+)/i);
  if (templateMatch) settings.template = templateMatch[1].trim();

  const platformMatch = userPrompt.match(/Platform:\s*([^\n]+)/i);
  if (platformMatch) settings.platform = platformMatch[1].trim();

  const brandColorMatch = userPrompt.match(/Brand color:\s*([^\n]+)/i);
  if (brandColorMatch) settings.brand_color = brandColorMatch[1].trim();

  const countMatch = userPrompt.match(/Number of slides:\s*(\d+)/i);
  if (countMatch) settings.slideCount = Number.parseInt(countMatch[1], 10);

  return settings;
}

function resolveTemplate(raw: string | undefined): 'primary' | 'secondary' {
  if (!raw) return brand.defaultTheme;
  const normalized = raw.toLowerCase().trim();
  // Match either the theme key or the theme label so older "Template: Cream" prompts still resolve.
  if (normalized === 'secondary' || normalized === brand.themes.secondary.label.toLowerCase()) {
    return 'secondary';
  }
  if (normalized === 'primary' || normalized === brand.themes.primary.label.toLowerCase()) {
    return 'primary';
  }
  return brand.defaultTheme;
}

function pickAccent(template: 'primary' | 'secondary'): string {
  return brand.themes[template].accent;
}

function buildMockCarousel(userPrompt: string) {
  const settings = parseUserSettings(userPrompt);
  const template = resolveTemplate(settings.template);
  const platform =
    settings.platform === 'instagram' || settings.platform === 'linkedin' || settings.platform === 'both'
      ? settings.platform
      : 'both';
  const requested = settings.slideCount ?? 5;
  const slideCount = Math.max(1, Math.min(8, requested));
  const accent = pickAccent(template);

  const slides: DemoSlide[] = [];
  for (let i = 0; i < slideCount; i++) {
    let templateIdx: number;
    if (i === 0) {
      templateIdx = 0;
    } else if (i === slideCount - 1) {
      templateIdx = DEMO_SLIDE_TEMPLATES.length - 1;
    } else {
      templateIdx = 1 + ((i - 1) % (DEMO_SLIDE_TEMPLATES.length - 2));
    }
    const tmpl = DEMO_SLIDE_TEMPLATES[templateIdx];
    slides.push({
      id: i + 1,
      type: tmpl.type,
      headline: tmpl.headline,
      subtext: tmpl.subtext,
      body: tmpl.body,
      eyebrow: tmpl.eyebrow,
      cta: tmpl.cta,
      visual_theme: tmpl.visual_theme,
      accent_color: accent,
      status: 'pending',
    });
  }

  return {
    topic: 'Demo carousel',
    template,
    brand_color: settings.brand_color || accent,
    platform,
    slides,
  };
}

export class DemoTextProvider implements TextProvider {
  async structure(input: TextStructureInput): Promise<unknown> {
    return buildMockCarousel(input.userPrompt);
  }
}

function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash + str.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

// Palette options for variety; the prompt's hash picks one deterministically.
const DEMO_PALETTES = [
  { start: '#0F1B3D', end: '#08122B', glowA: 'rgba(212, 168, 83, 0.32)', glowB: 'rgba(255, 255, 255, 0.10)' },
  { start: '#1A0F3D', end: '#0A0820', glowA: 'rgba(167, 139, 250, 0.30)', glowB: 'rgba(236, 72, 153, 0.18)' },
  { start: '#FAF7F2', end: '#E8DCC4', glowA: 'rgba(200, 164, 78, 0.28)', glowB: 'rgba(15, 27, 61, 0.14)' },
  { start: '#0B2A2F', end: '#04161A', glowA: 'rgba(94, 234, 212, 0.28)', glowB: 'rgba(251, 191, 36, 0.16)' },
  { start: '#3D1F0F', end: '#1C0D04', glowA: 'rgba(251, 146, 60, 0.34)', glowB: 'rgba(254, 215, 170, 0.18)' },
];

function buildDemoSvg(prompt: string, width: number, height: number): string {
  const seed = hashString(prompt);
  const palette = DEMO_PALETTES[seed % DEMO_PALETTES.length];
  const angle = (seed % 90) + 15;

  const cxA = ((seed >> 3) % 60) + 10;
  const cyA = ((seed >> 7) % 60) + 10;
  const cxB = 100 - cxA;
  const cyB = 100 - cyA;

  return `
    <svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" fill="none">
      <defs>
        <linearGradient id="bg" gradientTransform="rotate(${angle})">
          <stop offset="0%" stop-color="${palette.start}" />
          <stop offset="100%" stop-color="${palette.end}" />
        </linearGradient>
        <filter id="blur-xl" x="-30%" y="-30%" width="160%" height="160%">
          <feGaussianBlur stdDeviation="80" />
        </filter>
        <filter id="blur-md" x="-30%" y="-30%" width="160%" height="160%">
          <feGaussianBlur stdDeviation="40" />
        </filter>
      </defs>
      <rect width="${width}" height="${height}" fill="url(#bg)" />
      <ellipse cx="${Math.round(width * cxA / 100)}" cy="${Math.round(height * cyA / 100)}" rx="${Math.round(width * 0.32)}" ry="${Math.round(height * 0.18)}" fill="${palette.glowA}" filter="url(#blur-xl)" />
      <ellipse cx="${Math.round(width * cxB / 100)}" cy="${Math.round(height * cyB / 100)}" rx="${Math.round(width * 0.26)}" ry="${Math.round(height * 0.16)}" fill="${palette.glowB}" filter="url(#blur-xl)" />
      <circle cx="${Math.round(width * 0.5)}" cy="${Math.round(height * 0.5)}" r="${Math.round(width * 0.12)}" fill="${palette.glowA}" filter="url(#blur-md)" opacity="0.6" />
    </svg>
  `.trim();
}

export class DemoImageProvider implements ImageProvider {
  async generate(input: ImageGenerateInput): Promise<ImageGenerateResult> {
    const svg = buildDemoSvg(input.prompt, input.width, input.height);
    return {
      dataUrl: `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`,
      safetyFiltered: false,
    };
  }
}
